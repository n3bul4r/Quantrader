"""Generate the prop-firm economics tables used in docs/SYSTEM_DESIGN.md.

    python scripts/prop_economics.py [--paths 6000] [--eurusd 1.16]

Outputs docs/results/prop_economics.md and docs/results/prop_economics.json.
All trade models are ASSUMPTIONS (see qtengine/prop/simulator.py PRESET_MODELS);
replace them with EmpiricalTradeModel.from_trades(...) once you have real OOS trades.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

from qtengine.instruments import cost_report
from qtengine.prop import PRESET_MODELS, SimSizing, get_program, simulate_lifecycle
from qtengine.risk import ruin

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "results"

PROGRAMS = ["topstep_50k", "topstep_150k", "topstep_50k_static_labs", "apex_50k_eod", "apex_50k_intraday"]
MODELS = ["S1_planning", "S1_optimistic", "scalper_planning", "zero_edge"]
RISK_FRACS = [0.05, 0.075, 0.10, 0.15, 0.20, 0.25]


def fmt(x, d=0):
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "—"
    return f"{x:,.{d}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--paths", type=int, default=6000)
    ap.add_argument("--eurusd", type=float, default=1.16)
    ap.add_argument("--days", type=int, default=252)
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    md, js = [], {"eurusd": a.eurusd, "paths": a.paths, "horizon_days": a.days}

    md.append("# Prop-firm economics — Monte Carlo results\n")
    md.append(f"Generated by `engine/scripts/prop_economics.py` ({a.paths:,} paths per cell, {a.days}-trading-day horizon, "
              f"EURUSD assumed {a.eurusd}). Trade models are **assumptions**, not backtests — see SYSTEM_DESIGN.md §1. "
              "Rule presets are planning values from Nov-2026 secondary sources — verify before use.\n")

    # --- models
    md.append("## Trade models\n")
    md.append("| model | net E[R]/trade | PF (net) | win rate | trades/day | annual Sharpe | stop $/contract | cost $/RT |")
    md.append("|---|---|---|---|---|---|---|---|")
    js["models"] = {}
    for k in MODELS:
        s = PRESET_MODELS[k].summary()
        js["models"][k] = s
        md.append(f"| {k} | {s['expected_net_r']:+.3f} | {s['profit_factor_net']:.2f} | {s['net_win_rate']:.0%} | "
                  f"{s['trades_per_day']} | {s['annual_sharpe']:.2f} | {s['stop_dollars']:.0f} | {s['cost_per_contract']:.2f} |")

    # --- costs
    md.append("\n## Cost drag by trade geometry (MES / MNQ, all-in $1.40 fees + 2 ticks slippage per RT)\n")
    md.append("| setup | stop pts | target pts | risk $/ct | cost $/ct | cost % of risk | break-even win rate (net) |")
    md.append("|---|---|---|---|---|---|---|")
    geos = [("MES 8-tick scalp", "MES", 2, 2), ("MES 3:4 pt scalp", "MES", 3, 4), ("MES swing-intraday (S3-like)", "MES", 8, 12),
            ("MES S1 typical", "MES", 22, 40), ("MNQ 8-pt scalp", "MNQ", 8, 8), ("MNQ S1 typical", "MNQ", 60, 110)]
    js["costs"] = []
    for label, sym, sp, tp in geos:
        c = cost_report(sym, sp, tp)
        js["costs"].append({"label": label, **{k: v for k, v in c.__dict__.items() if k != "notes"}})
        md.append(f"| {label} | {sp} | {tp} | {c.risk_per_contract:.0f} | {c.cost_per_contract:.2f} | "
                  f"{c.cost_as_frac_of_risk:.1%} | {c.breakeven_winrate_net:.1%} |")

    # --- analytic anchors
    md.append("\n## Analytic anchors (Brownian approximation, 50K: target $3,000, trailing MLL $2,000 locking at start)\n")
    md.append("| daily mean $ | daily sd $ | daily Sharpe | P(+3000 before −2000, static) | P(reach MLL lock before trailing breach) | E[days to a $2,000 drawdown] |")
    md.append("|---|---|---|---|---|---|")
    js["analytic"] = []
    for mu, sd in [(0, 250), (10, 250), (20, 250), (30, 250), (20, 400), (50, 400)]:
        p1 = ruin.bm_prob_target_before_ruin(mu, sd, 3000, 2000)
        p2 = ruin.prob_reach_lock_before_trailing_breach(mu, sd, 2000, 2000)
        t = ruin.expected_time_to_trailing_breach(mu, sd, 2000)
        js["analytic"].append({"mu": mu, "sd": sd, "p_static": p1, "p_lock": p2, "days_to_dd": t})
        md.append(f"| {mu} | {sd} | {mu / sd:.3f} | {p1:.1%} | {p2:.1%} | {t:,.0f} |")

    # --- sweep + best
    js["sweeps"], js["best"] = {}, {}
    md.append("\n## Risk-per-trade sweep (1 account, 1 year of repeated attempts)\n")
    md.append("Net = trader's share of payouts − all evaluation/activation fees. Daily stop = 2R, max 3 consecutive losses, "
              "auto daily profit cap where a consistency rule applies.\n")
    for prog_key in PROGRAMS:
        prog = get_program(prog_key)
        md.append(f"\n### {prog.name}\n")
        md.append("| model | risk $/trade | net mean $ | net median $ | p05 $ | p95 $ | P(net>0) | P(≥1 payout) | pass rate/attempt | evals bought |")
        md.append("|---|---|---|---|---|---|---|---|---|---|")
        for mk in MODELS:
            rows = []
            for f in RISK_FRACS:
                risk = round(f * prog.evaluation.max_loss)
                res = simulate_lifecycle(prog, PRESET_MODELS[mk], SimSizing(risk_dollars=risk), n_paths=a.paths,
                                         horizon_days=a.days, record_paths=False, seed=7)
                rows.append({"risk": risk, **{k: res[k] for k in ("net_mean", "net_median", "net_p05", "net_p95", "p_net_positive",
                                                                     "p_any_payout", "pass_rate_per_attempt", "evals_bought_mean",
                                                                     "fees_mean", "payouts_mean", "median_day_first_payout")}})
            js["sweeps"][f"{prog_key}|{mk}"] = rows
            best = max(rows, key=lambda r: r["net_mean"])
            js["best"][f"{prog_key}|{mk}"] = best
            for r in rows:
                star = " **★**" if r is best else ""
                md.append(f"| {mk} | {r['risk']}{star} | {fmt(r['net_mean'])} | {fmt(r['net_median'])} | {fmt(r['net_p05'])} | "
                          f"{fmt(r['net_p95'])} | {r['p_net_positive']:.0%} | {r['p_any_payout']:.0%} | "
                          f"{r['pass_rate_per_attempt']:.0%} | {r['evals_bought_mean']:.1f} |")

    # --- income table
    md.append("\n## What it takes to hit a daily income target (EV-optimal risk, copy-traded accounts)\n")
    md.append(f"€/day = net mean ÷ {a.days} trading days ÷ EURUSD {a.eurusd}. Copy-trading N accounts multiplies the mean AND the "
              "dispersion: the accounts are perfectly correlated, so they fail together.\n")
    md.append("| program | model | best risk $ | net €/day per account (mean) | (median) | accounts for €20/day | €50/day | €100/day | €300/day | max accounts |")
    md.append("|---|---|---|---|---|---|---|---|---|---|")
    js["income"] = []
    for prog_key in PROGRAMS:
        prog = get_program(prog_key)
        for mk in MODELS:
            b = js["best"][f"{prog_key}|{mk}"]
            eur_day = b["net_mean"] / a.days / a.eurusd
            eur_med = b["net_median"] / a.days / a.eurusd

            def need(target):
                if eur_day <= 0:
                    return "∞"
                n = math.ceil(target / eur_day)
                return f"{n}" + ("" if n <= prog.max_accounts else " ✗")
            js["income"].append({"program": prog_key, "model": mk, "risk": b["risk"], "eur_day_mean": eur_day, "eur_day_median": eur_med})
            md.append(f"| {prog_key} | {mk} | {b['risk']} | {eur_day:,.2f} | {eur_med:,.2f} | {need(20)} | {need(50)} | {need(100)} | {need(300)} | {prog.max_accounts} |")
    md.append("\n✗ = exceeds the firm's maximum number of simultaneous accounts.\n")

    (OUT / "prop_economics.md").write_text("\n".join(md) + "\n")
    (OUT / "prop_economics.json").write_text(json.dumps(js, indent=1, default=float))
    print("\n".join(md))


if __name__ == "__main__":
    main()
